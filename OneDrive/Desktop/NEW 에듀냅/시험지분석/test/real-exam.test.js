test('고덕중 난이도 분포가 학원 카드의 도넛 그림과 같다', () => {
  const s = examStats(고덕중2);
  // 상 4 · 중상 4 · 중 14 · 하 5 (카드에 적힌 숫자 그대로). 중하는 쓰지 않은 학교다
  assert.deepEqual(s.byDifficulty.map((r) => [r.label, r.count]), [['하', 5], ['중', 14], ['중상', 4], ['상', 4]]);

  // 학원은 글 첫 줄에 "전체 난이도는 중상"이라고 썼지만, **학원 자신의 분포로 평균을 내도 '중'**이다
  // ((0×5 + 2×14 + 3×4 + 4×4) / 27 = 2.07). 헤드라인 난이도는 산술 평균이 아니라 판단이다 —
  // 상위 문항과 서답형 35점의 부담이 체감을 끌어올린다.
  // 우리는 계산을 부풀리지 않는다. 숫자는 '중'으로 두고, '중상'이라는 말은 AI 가 쓰는 총평과
  // 원장님이 고칠 수 있는 제목에 맡긴다.
  assert.equal(s.overall, '중');
  assert.equal(s.overallLabel, '보통');
  assert.equal(s.hardPct, 30); // 중상 이상 8/27 — 총평이 "중상"이라고 말할 근거는 이쪽이다
});

test('서답형을 묻는 내용의 영역으로 세면 어법이 실제 비중대로 나온다', () => {
  const s = examStats(고덕중2);
  const 어법 = s.byArea.find((r) => r.label === '어법');
  // 선택형 8 + 서답형 4 = 12문항. 서답형을 따로 뗐다면 8문항으로 줄어 시험을 잘못 읽는다
  assert.equal(어법.count, 12);
  assert.equal(s.byArea.reduce((n, r) => n + r.count, 0), 27);
});

test('배점이 낮아도 어려운 문항이 있다 — 두 눈금을 합치지 않는 이유', () => {
  const s = examStats(고덕중2);
  // 글: "21번은 3점이 배점된 상위 문항" — 이 시험에서 가장 낮은 배점인데 난이도는 상이다.
  const 스물한번 = 고덕중2.find((it) => it.no === '21');
  assert.equal(스물한번.points, 3);
  assert.equal(스물한번.difficulty, '상');
  // 배점 눈금으로는 표준인데 체감은 상 — 이런 문항이 변별 문항이다
  assert.ok(s.byWeight.find((r) => r.label === '표준').nos.includes('21'));
});
