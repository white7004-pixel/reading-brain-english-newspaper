  assert.equal(s.essayPointsPct, 0);
  assert.deepEqual(s.byKind.map((r) => [r.label, r.count]), [['객관식', 21]]);
  // 영역별: 독해 11 · 어휘 4 · 어법 4 · 대화문 2
