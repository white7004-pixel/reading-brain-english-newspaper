export const CURRICULUM = books.map(([book, title, chapters]) => ({
  book,
  title,
  chapters: chapters.map(([chapterTitle, units], chapterIndex) => {
    const chapter = `b${book}-c${chapterIndex + 1}`;
    return {
      id: chapter,
      title: chapterTitle,
      units: units.map(([unitTitle, page], unitIndex) => ({
        id: `${chapter}-u${unitIndex + 1}`,
        title: unitTitle,
        pageReference: `교재 ${page}쪽`
      }))
    };
  })
}));

export const ALL_UNITS = CURRICULUM.flatMap(book => book.chapters.flatMap(chapter =>
  chapter.units.map(unit => ({ ...unit, book: book.book, chapter: chapter.id, chapterTitle: chapter.title }))
));
